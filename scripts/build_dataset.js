// Enrich with subjectName, keywords, wordCount
const stopWords = new Set(['the','and','for','that','with','this','from','which','have','what','discuss','evaluate','examine','critically','analyze','explain','highlight','assess','clarify','account','elaborate','between','their','would','should','these','those','been']);

const processedQuestions = rawQuestions.map(q => {
  const sub = subMap[q.subjectId] || { name: "General Studies" };
  const words = q.text.toLowerCase().replace(/[^a-zA-Z0-9\s]/g, '').split(/\s+/).filter(w => w.length > 2 && !stopWords.has(w));
  const tagWords = q.tags.map(t => t.toLowerCase());
  const allKeywords = Array.from(new Set([...words, ...tagWords]));

  return {
    ...q,
    subjectName: sub.name,
    keywords: allKeywords,
    wordCount: q.text.trim().split(/\s+/).length,
  };
});

// Compute Tags Frequency
const tagMap = {};
processedQuestions.forEach(q => {
  q.tags.forEach(t => {
    tagMap[t] = (tagMap[t] || 0) + 1;
  });
});
const tagsList = Object.keys(tagMap).map(k => ({ tag: k, count: tagMap[k] })).sort((a,b) => b.count - a.count);

// Compute Related Questions Map
const relatedMap = {};
processedQuestions.forEach(q => {
  const matches = [];
  processedQuestions.forEach(other => {
    if (other.id === q.id) return;
    const tagOverlap = q.tags.filter(t => other.tags.includes(t));
    const kwOverlap = q.keywords.filter(k => other.keywords.includes(k));
    const sameSub = q.subjectId === other.subjectId ? 1 : 0;
    const crossPaperBonus = q.paperId !== other.paperId ? 1.5 : 0.5;
    const yearProx = 1 / (1 + Math.abs(q.year - other.year) * 0.1);

    const score = tagOverlap.length * 3 + kwOverlap.length * 2 + sameSub * 1 + crossPaperBonus + yearProx * 0.25;

    if (score >= 2.5) {
      matches.push({
        questionId: other.id,
        score: Math.round(score * 10) / 10,
        relevanceLevel: score >= 6 ? 'high' : 'moderate',
        matchingTags: tagOverlap,
        matchingKeywords: kwOverlap.slice(0, 5),
      });
    }
  });

  matches.sort((a,b) => b.score - a.score);
  relatedMap[q.id] = matches.slice(0, 10);
});

// Write outputs
const dataDir = path.join(__dirname, '../src/data');
fs.writeFileSync(path.join(dataDir, 'questions.json'), JSON.stringify(processedQuestions, null, 2));
fs.writeFileSync(path.join(dataDir, 'tags.json'), JSON.stringify(tagsList, null, 2));
fs.writeFileSync(path.join(dataDir, 'related-map.json'), JSON.stringify(relatedMap, null, 2));

